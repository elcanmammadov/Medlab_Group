// Fade animations
function initFade() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) e.target.classList.add('visible');
      });
    },
    { threshold: 0.1 },
  );
  document.querySelectorAll('.fade-in').forEach((el) => observer.observe(el));
}

// ── Hero Image Slider ──
let currentSlide = 0;
let sliderInterval;

function getSlideCount() {
  return document.querySelectorAll('.hero-slider .slide').length;
}

function showSlide(index) {
  const slides = document.querySelectorAll('.hero-slider .slide');
  const dots   = document.querySelectorAll('#sliderDots .dot');
  const total  = slides.length;
  if (!total) return;

  slides.forEach((s) => s.classList.remove('active'));
  dots.forEach((d)   => d.classList.remove('active'));

  currentSlide = ((index % total) + total) % total;
  slides[currentSlide].classList.add('active');
  if (dots[currentSlide]) dots[currentSlide].classList.add('active');
}

function moveSlide(dir) {
  showSlide(currentSlide + dir);
  resetSliderInterval();
}

function goToSlide(index) {
  showSlide(index);
  resetSliderInterval();
}

function startSlider() {
  clearInterval(sliderInterval);
  sliderInterval = setInterval(() => showSlide(currentSlide + 1), 4000);
}

function resetSliderInterval() {
  clearInterval(sliderInterval);
  startSlider();
}

// Fallback slides used when API returns nothing
const FALLBACK_SLIDES = [
  'image/medsun.jpg',
  'image/medlab.jpg',
  'image/Medlab_group.jpeg',
];

async function loadHeroSlides() {
  const sliderEl = document.getElementById('heroSlider');
  const dotsEl   = document.getElementById('sliderDots');
  if (!sliderEl || !dotsEl) return;

  let images = [];
  try {
    const base = (location.protocol === 'file:' ||
      (location.hostname === 'localhost' && location.port && location.port !== '5000'))
      ? 'http://localhost:5000' : '';
    const res  = await fetch(`${base}/api/hero-slides`);
    const data = await res.json();
    if (data.success && data.data.length) {
      images = data.data.map((s) => {
        const p = s.image || '';
        return p.startsWith('http') ? p : window.location.origin + p;
      });
    }
  } catch (_) { /* silently fall back */ }

  if (!images.length) images = FALLBACK_SLIDES;

  // Inject slides (insert before the arrow buttons)
  const prevBtn = sliderEl.querySelector('.slider-prev');
  images.forEach((src, i) => {
    const div = document.createElement('div');
    div.className = 'slide' + (i === 0 ? ' active' : '');
    div.style.backgroundImage = `url('${src}')`;
    sliderEl.insertBefore(div, prevBtn);
  });

  // Inject dots
  dotsEl.innerHTML = images
    .map((_, i) => `<span class="dot${i === 0 ? ' active' : ''}" onclick="goToSlide(${i})"></span>`)
    .join('');

  startSlider();
}

document.addEventListener('DOMContentLoaded', () => {
  setLang(currentLang);
  navTo('home');
  initFade();
  loadHeroSlides();

  const contactForm = document.getElementById('contactForm');
  if (contactForm) {
    contactForm.addEventListener('submit', async function (e) {
      e.preventDefault();
      const btn = this.querySelector('[type="submit"]');
      btn.disabled = true;
      try {
        const apiBase = (location.protocol === 'file:' ||
          (location.hostname === 'localhost' && location.port && location.port !== '5000'))
          ? 'http://localhost:5000' : '';
        const body = {
          name: this.name.value.trim(),
          email: this.email.value.trim(),
          phone: this.phone.value.trim(),
          message: this.message.value.trim(),
        };
        const res = await fetch(apiBase + '/api/contact', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(body),
        });
        const data = await res.json();
        if (data.success) {
          showToast('Mesaj uğurla göndərildi!');
          this.reset();
        } else {
          throw new Error(data.message || 'Xəta baş verdi');
        }
      } catch (err) {
        showToast(err.message);
      } finally {
        btn.disabled = false;
      }
    });
  }
});
