function showToast(msg) {
  let t = document.getElementById('toast');
  if (!t) {
    t = document.createElement('div');
    t.id = 'toast';
    t.style.cssText =
      'position:fixed;bottom:24px;right:24px;background:var(--text-dark);color:#fff;padding:12px 20px;border-radius:10px;font-size:.9rem;box-shadow:0 8px 20px rgba(0,0,0,.2);z-index:3000;transition:all .3s ease;transform:translateY(20px);opacity:0';
    document.body.appendChild(t);
  }
  t.textContent = msg;
  t.style.transform = 'translateY(0)';
  t.style.opacity = '1';
  setTimeout(() => {
    t.style.transform = 'translateY(20px)';
    t.style.opacity = '0';
  }, 3000);
}

